"""Stage 4 evaluation of find_enforcement_precedent on aip.evals.

Three kinds of case: a described risk with known precedents (from the Stage 1 labels), a risk with
none in the corpus, and a gap finding produced by check_policy_gap. Scored against a Stage 1-style
baseline that returns the top retrieved case as the precedent, which is what "retrieval alone"
would claim. The difference is the value of the relevance judgement.
"""
from __future__ import annotations

import json

from aip.cost import Budget
from aip.evals import Case, refusal_metrics, run_eval

from regtech.enforcement import load_cases as load_case_table
from regtech.paths import EVAL_DIR, REPORTS_DIR
from regtech.precedent import PrecedentFinder, PrecedentReport


def load_precedent_cases() -> list[Case]:
    rows = [json.loads(x) for x in (EVAL_DIR / "precedent_cases.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    known = set(load_case_table())
    bad = [f"{r['id']}: unknown case {d}" for r in rows for d in r["expected"] if d not in known]
    if bad:
        raise ValueError("precedent cases have problems:\n  " + "\n  ".join(bad))
    return [Case(r["id"], {k: r[k] for k in ("risk", "gap", "max_cases") if k in r}, r["expected"], {"kind": r["kind"]})
            for r in rows]


def metric(out: dict, expected: list[str]) -> dict[str, float]:
    got = [p["case_id"] for p in out["precedents"]]
    top = out["candidates_considered"][:1]
    m = {"no_precedent": float(out["no_precedent"]), "baseline_claimed_precedent": float(bool(top))}
    if expected:
        hit = set(expected) & set(got)
        m["recall"] = len(hit) / len(expected)
        m["hit_at_1"] = float(bool(got) and got[0] in expected)
        if got:
            m["precision"] = len(hit) / len(got)
        m["baseline_hit_at_1"] = float(bool(top) and top[0] in expected)
    else:
        m["correct_no_precedent"] = float(out["no_precedent"])
        m["false_precedent"] = float(not out["no_precedent"])
        m["baseline_false_precedent"] = float(bool(top))
    return m


def _mean(results, key) -> float:
    vals = [r.metrics[key] for r in results if key in r.metrics]
    return sum(vals) / len(vals) if vals else float("nan")


def run() -> dict:
    cases = load_precedent_cases()
    finder = PrecedentFinder()
    with Budget(limit_usd=0.5, label="stage4-eval") as b:
        rep = run_eval("stage4:precedent", cases, lambda inp: finder.find(inp).model_dump(mode="json"), metric,
                       budget_usd=0.5, progress=False)
    errors = [r for r in rep.results if r.error]
    if errors:
        raise RuntimeError(f"{len(errors)} case(s) errored, e.g. {errors[0].error}")
    res = rep.results
    by_id = {c.id: c for c in cases}
    kinds = {c.id: c.meta["kind"] for c in cases}
    refusal = refusal_metrics([r.output["no_precedent"] for r in res], [not by_id[r.id].expected for r in res])
    agg = {k: _mean(res, k) for k in ("recall", "precision", "hit_at_1", "correct_no_precedent", "false_precedent",
                                       "baseline_hit_at_1", "baseline_false_precedent")}
    costs = [r.output["cost_usd"] for r in res]

    def f(x, d=2):
        return "n/a" if x != x else f"{x:.{d}f}"

    pos = [r for r in res if by_id[r.id].expected]
    neg = [r for r in res if not by_id[r.id].expected]
    out = [
        "# Stage 4 - find_enforcement_precedent evaluation", "",
        "Generated by `python -m regtech eval-precedent` (`aip.evals.run_eval`). "
        f"{len(cases)} cases: {sum(k == 'precedent' for k in kinds.values())} risks with known precedents "
        f"(Stage 1 labels), {sum(k == 'no_precedent' for k in kinds.values())} risks with none in the corpus, "
        f"{sum(k == 'gap' for k in kinds.values())} gap findings fed in from check_policy_gap.", "",
        "Baseline = what retrieval alone would claim: the top-ranked penalty case, always.", "",
        "| Metric | Baseline (top hit) | Tool |", "|---|---:|---:|",
        f"| Right precedent ranked first (risks with precedents, n={len(pos)}) | {f(agg['baseline_hit_at_1'])} | {f(agg['hit_at_1'])} |",
        f"| Recall of known precedents | - | {f(agg['recall'])} |",
        f"| Precision of returned precedents | - | {f(agg['precision'])} |",
        f"| Said 'no precedent' when there is none (n={len(neg)}) | 0.00 | {f(agg['correct_no_precedent'])} |",
        f"| **Claimed a precedent that does not exist** | {f(agg['baseline_false_precedent'])} | **{f(agg['false_precedent'])}** |",
        f"| 'No precedent' precision: right / all such answers | - | {f(refusal['refusal_precision'])} "
        f"({int(refusal['refused_correctly'])}/{int(refusal['refused_total'])}) |",
        f"| Cost per query | - | ${sum(costs) / len(costs):.4f} |", "",
        "## Per case", "", "| Case | Kind | Expected | Returned precedents | Related | OK |", "|---|---|---|---|---|---|",
    ]
    for r in res:
        exp = by_id[r.id].expected
        got = [p["case_id"] for p in r.output["precedents"]]
        rel = [p["case_id"] for p in r.output["related"]]
        ok = (set(exp) <= set(got) and (not got or set(got) <= set(exp))) if exp else r.output["no_precedent"]
        short = lambda ids: ", ".join(i.replace("enf-", "") for i in ids) or "none"  # noqa: E731
        out.append(f"| {r.id} | {kinds[r.id]} | {short(exp)} | {short(got)} | {short(rel)} | {'yes' if ok else '**no**'} |")
    x01 = next((r.output for r in res if r.id == "X01"), None)
    if x01:
        out += ["", "## Example: chained from check_policy_gap (IIFL, gold loan auctions)", "", "```text",
                PrecedentReport.model_validate(x01).render(), "```"]
    out += ["", f"Evaluation cost: ${b.spent_usd:.4f} ({b.calls} model calls, {b.cached_calls} from cache).", ""]
    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "stage4_precedent.md").write_text("\n".join(out), encoding="utf-8")
    (REPORTS_DIR / "stage4_precedent.json").write_text(json.dumps(
        {"aggregate": agg, "refusal": refusal, "per_case": {r.id: {"metrics": r.metrics, "output": r.output} for r in res}},
        indent=2, default=str), encoding="utf-8")
    return {"aggregate": agg, "refusal": refusal}
