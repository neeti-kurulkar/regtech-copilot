"""Stage 5 evaluation, Lab 2 method: compare extraction variants on a fully labelled dev set, then lock one.

Dev set: 11 heading sections with EVERY deadline hand-labelled (17 items), including sections that
contain none (a worked example) and non-deadlines that look like deadlines (classification
thresholds, a minimum tenure, historical dates). Items are matched one-to-one by quote overlap, so a
merged item cannot claim credit for three obligations. Fields checked: kind, and the figure(s) the
gold item names (days, years, frequency, due date, offset, weekday).
"""
from __future__ import annotations

import json

from aip.cost import Budget
from aip.evals import Case, EvalReport, compare, run_eval
from aip.guards import quote_in_source

from regtech.deadlines import extract_section
from regtech.index import build_chunks
from regtech.paths import EVAL_DIR, REPORTS_DIR

VARIANTS = [("A", "SMALL"), ("A", "MAIN"), ("B", "SMALL"), ("B", "MAIN")]
FIELD_MAP = {"days": "within_days", "n_years": "n_years", "frequency": "frequency", "due_date": "due_date",
             "offset_days": "offset_days", "weekday": "weekday"}


def load_dev() -> list[Case]:
    rows = [json.loads(x) for x in (EVAL_DIR / "deadline_dev.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    chunks = {c.chunk_id: c for c in build_chunks("regulation", "markdown", 1500)}
    for r in rows:
        text = chunks[r["chunk_id"]].text
        for it in r["items"]:
            if not quote_in_source(it["evidence"], text, 0.6):
                raise ValueError(f"{r['id']}: evidence not in {r['chunk_id']}: {it['evidence']!r}")
    return [Case(r["id"], r["chunk_id"], r["items"], {"note": r["note"]}) for r in rows]


def _overlaps(evidence: str, quote: str) -> bool:
    return quote_in_source(evidence, quote, 0.6) or quote_in_source(quote, evidence, 0.6)


def match(pred: list[dict], gold: list[dict]) -> tuple[int, int, int]:
    """(true positives, items with every labelled field right, items with the right kind)."""
    used: set[int] = set()
    tp = fields_ok = kind_ok = 0
    for g in gold:
        j = next((i for i, p in enumerate(pred) if i not in used and _overlaps(g["evidence"], p["quote"])), None)
        if j is None:
            continue
        used.add(j)
        tp += 1
        p = pred[j]
        k = p["kind"] in g["kind"]
        kind_ok += k
        vals_ok = all(str(p.get(FIELD_MAP[f])) in {str(v) for v in g[f]} for f in FIELD_MAP if f in g)
        fields_ok += k and vals_ok
    return tp, fields_ok, kind_ok


def metric(pred: list[dict], gold: list[dict]) -> dict[str, float]:
    tp, fields_ok, kind_ok = match(pred, gold)
    return {"tp": float(tp), "n_pred": float(len(pred)), "n_gold": float(len(gold)),
            "fields_ok": float(fields_ok), "kind_ok": float(kind_ok)}


def micro(rep: EvalReport) -> dict[str, float]:
    s = {k: sum(r.metrics.get(k, 0.0) for r in rep.results) for k in ("tp", "n_pred", "n_gold", "fields_ok", "kind_ok")}
    p = s["tp"] / s["n_pred"] if s["n_pred"] else 0.0
    r = s["tp"] / s["n_gold"] if s["n_gold"] else 0.0
    return {**s, "precision": p, "recall": r, "f1": 2 * p * r / (p + r) if p + r else 0.0,
            "field_accuracy": s["fields_ok"] / s["tp"] if s["tp"] else 0.0,
            "false_items_on_trap_sections": sum(r_.metrics.get("n_pred", 0) for r_ in rep.results if r_.id == "D09")}


def run() -> dict:
    cases = load_dev()
    chunks = {c.chunk_id: c for c in build_chunks("regulation", "markdown", 1500)}
    reports, rows = [], []
    for prompt, tier in VARIANTS:
        with Budget(limit_usd=0.5, label=f"stage5:{prompt}-{tier}") as b:
            rep = run_eval(f"{prompt}-{tier}", cases,
                           lambda cid, p=prompt, t=tier: [r.model_dump(mode="json") for r in extract_section(chunks[cid], p, t)],
                           metric, budget_usd=0.5, progress=False)
        m = micro(rep)
        rep_for_compare = EvalReport(rep.name, [type(x)(x.id, x.output, {"precision_case": (x.metrics["tp"] / x.metrics["n_pred"]) if x.metrics.get("n_pred") else 1.0,
                                                                       "recall_case": (x.metrics["tp"] / x.metrics["n_gold"]) if x.metrics.get("n_gold") else 1.0},
                                                        x.error, x.latency_ms) for x in rep.results], rep.budget)
        reports.append(rep_for_compare)
        rows.append({"variant": f"{prompt}-{tier}", **m, "cost_usd": b.spent_usd, "calls": b.calls,
                     "p95_ms": rep.latency_percentile(95), "outputs": {x.id: x.output for x in rep.results}})
    best = max(rows, key=lambda r: (round(r["f1"], 3), round(r["field_accuracy"], 3), -r["cost_usd"]))
    out = ["# Stage 5 - Deadline extraction: variant comparison (Lab 2)", "",
           "Generated by `python -m regtech eval-deadlines`. Four variants of `extract_deadlines` run over a",
           "fully hand-labelled dev set (`data/eval/deadline_dev.jsonl`: 11 sections, 17 deadlines, plus",
           "trap content: a worked example with sample dates, classification thresholds, a minimum tenure,",
           "historical dates). Prompt A = kinds only; prompt B = kinds + field rules + explicit exclusions.",
           "SMALL = gemini-3.5-flash-lite (no reasoning); MAIN = gemini-3.7-flash (reasoning).", "",
           "| Variant | Precision | Recall | F1 | Fields right (of matched) | Items on the worked example | Cost | p95 ms |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    out += [f"| {r['variant']} | {r['precision']:.2f} ({int(r['tp'])}/{int(r['n_pred'])}) | {r['recall']:.2f} ({int(r['tp'])}/{int(r['n_gold'])}) | "
            f"{r['f1']:.2f} | {r['field_accuracy']:.2f} | {int(r['false_items_on_trap_sections'])} | ${r['cost_usd']:.4f} | {r['p95_ms']:,.0f} |"
            for r in rows]
    out += ["", f"**Selected default: `{best['variant']}`** (best F1, then field accuracy, then cost).", "",
            "Per-section averages from `aip.evals.compare`:", "", "```text",
            compare(*reports, metrics=["precision_case", "recall_case"]), "```", ""]
    (REPORTS_DIR / "stage5_deadline_variants.md").write_text("\n".join(out), encoding="utf-8")
    (REPORTS_DIR / "stage5_deadline_variants.json").write_text(json.dumps(rows, indent=2, default=str), encoding="utf-8")
    return {"rows": rows, "best": best["variant"]}


AUDIT_CSV = REPORTS_DIR / "stage5_calendar_audit.csv"


def write_audit(n: int = 20, seed: int = 7) -> list[dict]:
    """A seeded random sample of calendar entries for a precision audit of the FULL calendar.

    The dev set measures 11 hand-picked sections; this checks the other ~200 the extractor saw.
    Columns: the entry, its verbatim quote, the whole source section, then verdict columns.
    """
    import csv
    import random

    from regtech.deadlines import load_calendar

    recs = load_calendar()
    chunks = {c.chunk_id: c.text for c in build_chunks("regulation", "markdown", 1500)}
    sample = random.Random(seed).sample(recs, min(n, len(recs)))
    rows = []
    for r in sample:
        fields = {k: v for k, v in r.model_dump(mode="json").items()
                  if k in ("due_date", "frequency", "n_years", "offset_days", "offset_months", "weekday", "trigger",
                           "within_days", "within_months", "working_days") and v not in (None, False)}
        rows.append({"id": r.id, "kind": r.kind, "obligation": r.obligation, "fields": json.dumps(fields),
                     "quote": r.quote, "source": r.source, "section_text": chunks.get(r.chunk_id, "")[:2500],
                     "is_real_deadline_Y_N": "", "fields_right_Y_N": "", "note": ""})
    with AUDIT_CSV.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return rows
